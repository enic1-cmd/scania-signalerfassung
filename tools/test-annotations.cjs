    assert(range.end>range.start);assert.equal(range.color,'#4aaadd');
    await page.locator('.annotation-note').click();
    await page.locator('.annotation-dialog textarea').fill('Lastwechsel im markierten Zeitraum.');
    await page.locator('.annotation-dialog button[type="submit"]').click();
    await page.mouse.move(b.x,b.y);await page.mouse.down();await page.mouse.move(a.x,a.y,{steps:4});await page.keyboard.press('Escape');await page.mouse.up();
    assert.equal(await page.evaluate(()=>active().ranges.length),1,'Escape must cancel range');
    await page.locator('#view-table-btn').click();
    await page.evaluate(()=>{const entry=active().ranges[0];document.getElementById('table-wrap').scrollTop=(document.getElementById('thead').getBoundingClientRect().height||0)+(entry.start+20)*TABLE_ROW_HEIGHT;});
    await page.waitForTimeout(200);
    assert(await page.locator('tr.row-annotated').count()>0,'Range must be tinted in table');
    await page.locator('.row-note').first().click();
    await page.locator('.annotation-dialog textarea').fill('Notiz aus der Tabelle');
    await page.locator('.annotation-dialog button[type="submit"]').click();
    const snapshot=await page.evaluate(()=>projectSnapshot());
    assert.equal(snapshot.files[0].annotations.ranges[0].note,'Lastwechsel im markierten Zeitraum.');
    assert.equal(snapshot.files[0].annotations.rows.filter(r=>r.note).length,2);
    page.once('dialog',dialog=>dialog.accept());
    await page.locator('#project-input').setInputFiles({name:'Test.signalprojekt',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(snapshot))});
    await page.waitForFunction(()=>active()!==window.annotationPreviousFile&&active().ranges?.[0]?.note==='Lastwechsel im markierten Zeitraum.');
    assert.deepEqual(await page.evaluate(()=>Annotations.snapshot(active()).rows),snapshot.files[0].annotations.rows);
    assert.equal(await page.evaluate(()=>active().ranges[0].color),'#4aaadd');
    assert.equal(await page.evaluate(()=>active().rawRows.filter(r=>r.marked).length),1);
