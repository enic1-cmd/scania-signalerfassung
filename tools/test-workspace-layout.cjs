const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const {chromium}=require('playwright');
const root=path.resolve(__dirname,'..');
new Function(fs.readFileSync(path.join(root,'assets/workspace-layout.js'),'utf8'));
(async()=>{
  const browser=await chromium.launch({headless:true,channel:'chrome'});
  try{
    const page=await browser.newPage({viewport:{width:1500,height:850}}),errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    await page.goto(pathToFileURL(path.join(root,'signalerfassung-analyse-tool.html')).href);
    await page.locator('#file-input').setInputFiles(path.join(root,'samples/Test_signalerfassung.txt'));
    await page.waitForFunction(()=>document.body.classList.contains('analysis-workspace'));
    await page.locator('#view-chart-btn').click();
    await page.waitForTimeout(250);
    const initial=await page.locator('#analysis-surface').boundingBox();
    assert(initial.height>550,'Normal mode should leave most of the viewport for analysis');
    await page.locator('#workspace-signals').click();
    await page.waitForFunction(()=>!document.getElementById('workspace-panel-signals').hidden);
    assert.equal((await page.locator('#analysis-surface').boundingBox()).height,initial.height);
    await page.locator('#workspace-filters').click();
    assert.equal(await page.locator('#workspace-panel-signals').isVisible(),false);
    await page.locator('#f-search').fill('16:56');
    assert(await page.locator('#workspace-filters').evaluate(n=>n.classList.contains('has-filter')));
    await page.locator('#workspace-meta').click();
    assert.equal(await page.locator('#workspace-panel-filters').isVisible(),false);
    await page.locator('#workspace-meta').click();
    await page.locator('.annotation-toggle').click();
    await page.waitForTimeout(250);
    const side=await page.locator('.annotation-sidebar').boundingBox(),chart=await page.locator('#chart-wrap').boundingBox();
    assert(side.x>=chart.x+chart.width-1,'Sidebar must sit beside chart on desktop');
    assert.equal((await page.locator('#analysis-surface').boundingBox()).height,initial.height);
    await page.locator('.workspace-focus').click();
    const focused=await page.locator('#analysis-surface').boundingBox();
    assert(focused.height>initial.height+65,'Focus mode should gain header/footer space');
    assert.equal(await page.locator('body>header').isVisible(),false);
    assert.equal(await page.locator('#f-search').inputValue(),'16:56');
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('.annotation-sidebar').isVisible(),false);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('body>header').isVisible(),true);
    await page.locator('#workspace-filters').click();
    await page.locator('#f-search').fill('');
    await page.locator('#workspace-filters').click();
    await page.locator('#view-table-btn').click();
    await page.locator('.workspace-focus').click();
    assert(await page.locator('#tbody tr.data-row').count()>10,'Table must render after focus resize');
    await page.locator('#view-chart-btn').click();
    await page.waitForTimeout(300);
    await page.evaluate(()=>{window.layoutPaints=0;const original=renderChart;window.renderChart=function(){window.layoutPaints++;return original();};});
    await page.waitForTimeout(400);
    assert.equal(await page.evaluate(()=>window.layoutPaints),0,'No persistent resize/render loop');
    await page.setViewportSize({width:390,height:740});
    await page.waitForTimeout(250);
    assert(await page.locator('.workspace-focus').isVisible());
    assert(await page.locator('#analysis-surface').evaluate(n=>n.clientHeight>350),'Mobile focus must retain usable data area');
    await page.locator('.annotation-toggle').click();
    assert(await page.locator('.annotation-sidebar').isVisible());
    await page.getByRole('button',{name:'Notizen schließen'}).click();
    assert.equal(await page.locator('.annotation-sidebar').isVisible(),false);
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({result:'PASS',viewportHeight:850,normalDataHeight:initial.height,focusDataHeight:focused.height,sidebar:'no vertical space lost',mobile:'PASS',pageErrors:errors},null,2));
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
